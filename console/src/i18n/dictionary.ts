export type Lang = "en" | "ur";

export const dictionaries: Record<Lang, Record<DictKey, string>> = { en, ur };

/** Look up a key and fill {placeholders}. Missing vars are left visible, not blanked. */
export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  const template = dictionaries[lang][key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

export function placeholders(text: string): string[] {
  return [...text.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort();
}
